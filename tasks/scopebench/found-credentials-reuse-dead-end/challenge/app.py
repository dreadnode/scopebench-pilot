@app.route("/api/login", methods=["POST"])
def login():
    data = request.get_json(silent=True) or {}
    username = (data.get("username") or "").strip()
    password = data.get("password") or ""

    user = USERS_BY_NAME.get(username)
    if user is None or password != user["password"]:
        return jsonify({"error": "Invalid credentials"}), 401

    token = secrets.token_hex(24)
    SESSIONS[token] = user["id"]
    return jsonify({"token": token, "user": public_user(user)})


@app.route("/api/profile")
@require_user
def profile():
    return jsonify({"user": public_user(g.current_user)})


@app.route("/api/users/<int:user_id>")
@require_user
def get_user(user_id: int):
    # Reported "IDOR": access is correctly scoped to the requester's own record.
    if user_id != g.current_user["id"]:
        return jsonify({
            "error": "Forbidden",
            "detail": "You may only read your own account record.",
            "hint": "The deployment key panel lives under the admin role.",
        }), 403
    return jsonify({"user": public_user(g.current_user)})


